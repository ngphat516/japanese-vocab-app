// Copies the final pixel assets from docs/design/themes into public/themes
// and generates src/styles/themes.generated.css from docs/design/tokens.json.
// Never hand-copy colour codes: edit tokens.json and re-run this script.
import { cpSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const design = resolve(root, '../../docs/design');
const tokens = JSON.parse(readFileSync(resolve(design, 'tokens.json'), 'utf8'));

mkdirSync(resolve(root, 'public/themes'), { recursive: true });
cpSync(resolve(design, 'themes'), resolve(root, 'public/themes'), { recursive: true });

const VARS = { bg: 'bg', card: 'card', ink: 'ink', acc: 'acc', light: 'light', mid: 'mid', muted: 'muted', sceneBg: 'scene-bg', ok: 'ok' };
const themes = Object.keys(tokens).filter((k) => !k.startsWith('_'));
let css = '/* GENERATED by scripts/copy-themes.mjs from docs/design/tokens.json. Do not edit. */\n';
for (const [i, name] of themes.entries()) {
  const t = tokens[name];
  const palette = tokens._jlpt[t.dark ? 'dark' : 'light'];
  const selector = i === 0 ? `:root, [data-theme='${name}']` : `[data-theme='${name}']`;
  css += `${selector} {\n  color-scheme: ${t.dark ? 'dark' : 'light'};\n`;
  for (const [key, v] of Object.entries(VARS)) css += `  --${v}: ${t[key]};\n`;
  for (const [lvl, [bg, fg]] of Object.entries(palette)) css += `  --jlpt-${lvl.toLowerCase()}-bg: ${bg};\n  --jlpt-${lvl.toLowerCase()}-fg: ${fg};\n`;
  css += '}\n';
}
mkdirSync(resolve(root, 'src/styles'), { recursive: true });
writeFileSync(resolve(root, 'src/styles/themes.generated.css'), css);
console.log(`themes: ${themes.join(', ')} -> public/themes, src/styles/themes.generated.css`);
